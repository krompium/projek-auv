#!/usr/bin/env python3
"""Parity & accuracy checker for the on-device UAV waste-detection pipeline (U6).

Compares the device dump produced by DetectionHarness
(<externalFilesDir>/harness_predictions.jsonl) against:

  1. a REFERENCE dump of the same images produced on PC/Colab
     (generated by this script with --generate-reference, or exported
     from any other runner in the same JSONL schema), proving there is
     no systematic parsing / letterbox / NMS error on-device (R5); and
  2. ground-truth labels in YOLO txt format (Roboflow export), producing
     a precision/recall sweep over confidence thresholds so
     CONFIDENCE_THRESHOLD is chosen from data instead of guessed (R6).

JSONL schema (one row per image):
  {"image": "name.jpg", "detections": [
      {"box": [l, t, r, b], "label": "rubbish", "confidence": 0.87}]}
  box coordinates are normalized [0,1] on the ORIGINAL image.

Usage:
  # 1) On PC/Colab, generate the reference for the same image folder:
  python3 tools/parity_check.py --generate-reference \
      --model best_float16.tflite --images test_images/ \
      --out reference_predictions.jsonl

  # 2) Compare device vs reference (parity, R5):
  python3 tools/parity_check.py --device harness_predictions.jsonl \
      --reference reference_predictions.jsonl

  # 3) Accuracy vs Roboflow ground truth + threshold sweep (R6):
  python3 tools/parity_check.py --device harness_predictions.jsonl \
      --labels test_labels_dir/ --sweep 0.20:0.60:0.05
"""

import argparse
import json
import os
import sys
from collections import defaultdict

PARITY_IOU = 0.90          # per-box IoU required for parity (AE3)
PARITY_CONF_TOL = 0.05     # confidence agreement tolerance
PARITY_PASS_RATE = 0.95    # fraction of boxes that must reach parity
MATCH_IOU = 0.50           # IoU for PR matching (mAP@0.5 convention)


def iou(a, b):
    il, it = max(a[0], b[0]), max(a[1], b[1])
    ir, ib = min(a[2], b[2]), min(a[3], b[3])
    if ir <= il or ib <= it:
        return 0.0
    inter = (ir - il) * (ib - it)
    ua = (a[2] - a[0]) * (a[3] - a[1]) + (b[2] - b[0]) * (b[3] - b[1]) - inter
    return inter / ua if ua > 0 else 0.0


def load_jsonl(path):
    rows = {}
    with open(path) as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            row = json.loads(line)
            rows[row["image"]] = row.get("detections", [])
    return rows


def load_yolo_labels(labels_dir, image_names):
    """YOLO txt: 'cls cx cy w h' normalized. Returns image -> [[l,t,r,b], ...]."""
    gt = {}
    for name in image_names:
        stem = os.path.splitext(name)[0]
        path = os.path.join(labels_dir, stem + ".txt")
        boxes = []
        if os.path.exists(path):
            with open(path) as f:
                for line in f:
                    parts = line.split()
                    if len(parts) < 5:
                        continue
                    _, cx, cy, w, h = (float(x) for x in parts[:5])
                    boxes.append([cx - w / 2, cy - h / 2, cx + w / 2, cy + h / 2])
        gt[name] = boxes
    return gt


def check_parity(device, reference):
    """R5: per-box IoU >= 0.9, class match, confidence within tolerance."""
    total = matched = 0
    conf_deltas, offsets = [], []
    per_image_fail = []

    for image, ref_dets in sorted(reference.items()):
        dev_dets = device.get(image, [])
        used = [False] * len(dev_dets)
        image_fails = 0
        for rd in ref_dets:
            total += 1
            best, best_iou = None, 0.0
            for i, dd in enumerate(dev_dets):
                if used[i]:
                    continue
                v = iou(rd["box"], dd["box"])
                if v > best_iou:
                    best_iou, best = v, i
            if best is not None and best_iou >= PARITY_IOU \
                    and dev_dets[best].get("label") == rd.get("label") \
                    and abs(dev_dets[best]["confidence"] - rd["confidence"]) <= PARITY_CONF_TOL:
                used[best] = True
                matched += 1
                conf_deltas.append(dev_dets[best]["confidence"] - rd["confidence"])
                offsets.append([dev_dets[best]["box"][k] - rd["box"][k] for k in range(4)])
            else:
                image_fails += 1
        # phantom device boxes count as failures too
        phantoms = used.count(False)
        if image_fails or phantoms:
            per_image_fail.append((image, image_fails, phantoms))

    rate = matched / total if total else 1.0
    print("== PARITY (device vs reference) ==")
    print(f"reference boxes: {total}, matched at IoU>={PARITY_IOU}: {matched} "
          f"({rate:.1%}, required {PARITY_PASS_RATE:.0%})")
    if conf_deltas:
        mean_dc = sum(conf_deltas) / len(conf_deltas)
        print(f"mean confidence delta: {mean_dc:+.4f} (tol ±{PARITY_CONF_TOL})")
    if offsets:
        mean_off = [sum(o[k] for o in offsets) / len(offsets) for k in range(4)]
        print("mean box offset (l,t,r,b): "
              + ", ".join(f"{v:+.4f}" for v in mean_off))
        # Systematic offset flag: a constant shift must not be averaged away
        if any(abs(v) > 0.01 for v in mean_off):
            print("!! SYSTEMATIC OFFSET detected (>0.01 mean shift) — parity FAIL")
            return False
    for image, fails, phantoms in per_image_fail[:10]:
        print(f"  fail: {image}: unmatched_ref={fails} phantom_device={phantoms}")
    ok = rate >= PARITY_PASS_RATE
    print("PARITY:", "PASS" if ok else "FAIL")
    return ok


def pr_at_threshold(device, gt, thr):
    tp = fp = fn = 0
    for image, boxes_gt in gt.items():
        dets = [d for d in device.get(image, []) if d["confidence"] >= thr]
        dets.sort(key=lambda d: -d["confidence"])
        taken = [False] * len(boxes_gt)
        for d in dets:
            best, best_iou = None, 0.0
            for i, g in enumerate(boxes_gt):
                if taken[i]:
                    continue
                v = iou(d["box"], g)
                if v > best_iou:
                    best_iou, best = v, i
            if best is not None and best_iou >= MATCH_IOU:
                taken[best] = True
                tp += 1
            else:
                fp += 1
        fn += taken.count(False)
    prec = tp / (tp + fp) if tp + fp else 1.0
    rec = tp / (tp + fn) if tp + fn else 1.0
    return prec, rec, tp, fp, fn


def check_accuracy(device, labels_dir, sweep):
    gt = load_yolo_labels(labels_dir, device.keys())
    n_gt = sum(len(v) for v in gt.values())
    print(f"== ACCURACY vs ground truth ({len(gt)} images, {n_gt} GT boxes) ==")
    print(f"{'thr':>5} {'precision':>10} {'recall':>8} {'F1':>7} {'TP':>5} {'FP':>5} {'FN':>5}")
    best_thr, best_f1 = None, -1.0
    for thr in sweep:
        p, r, tp, fp, fn = pr_at_threshold(device, gt, thr)
        f1 = 2 * p * r / (p + r) if p + r else 0.0
        marker = ""
        if f1 > best_f1:
            best_f1, best_thr = f1, thr
            marker = "  <-- best F1"
        print(f"{thr:5.2f} {p:10.3f} {r:8.3f} {f1:7.3f} {tp:5d} {fp:5d} {fn:5d}{marker}")
    print(f"suggested operating threshold (max F1): {best_thr:.2f}")
    # simple AP@0.5 over the sweep (rough, monotonic interpolation)
    return best_thr


def generate_reference(model_path, images_dir, out_path):
    """Runs the same letterbox + tflite + NMS pipeline on PC (needs tensorflow)."""
    try:
        import numpy as np
        from PIL import Image
        try:
            from tflite_runtime.interpreter import Interpreter  # lightweight
        except ImportError:
            from tensorflow.lite import Interpreter  # type: ignore
    except ImportError as e:
        sys.exit(f"--generate-reference needs numpy, pillow and tflite: {e}")

    interp = Interpreter(model_path=model_path)
    interp.allocate_tensors()
    inp = interp.get_input_details()[0]
    outp = interp.get_output_details()[0]
    size = inp["shape"][1]  # 640

    with open(out_path, "w") as out:
        for name in sorted(os.listdir(images_dir)):
            if not name.lower().endswith((".jpg", ".jpeg", ".png")):
                continue
            img = Image.open(os.path.join(images_dir, name)).convert("RGB")
            sw, sh = img.size
            scale = min(size / sw, size / sh)
            cw, ch = round(sw * scale), round(sh * scale)
            px, py = (size - cw) // 2, (size - ch) // 2
            canvas = Image.new("RGB", (size, size), (114, 114, 114))
            canvas.paste(img.resize((cw, ch)), (px, py))
            x = np.asarray(canvas, dtype=np.float32)[None] / 255.0

            interp.set_tensor(inp["index"], x)
            interp.invoke()
            y = interp.get_tensor(outp["index"])[0]  # [4+C, 8400]

            dets = []
            scores = y[4:].max(axis=0)
            classes = y[4:].argmax(axis=0)
            keep = scores >= 0.35
            boxes = []
            for cx, cy, w, h, s, c in zip(y[0][keep], y[1][keep], y[2][keep],
                                          y[3][keep], scores[keep], classes[keep]):
                l = (cx - w / 2) * size
                t = (cy - h / 2) * size
                r = (cx + w / 2) * size
                b = (cy + h / 2) * size
                # inverse letterbox to original-normalized
                box = [max(0.0, min(1.0, (l - px) / (sw * scale))),
                       max(0.0, min(1.0, (t - py) / (sh * scale))),
                       max(0.0, min(1.0, (r - px) / (sw * scale))),
                       max(0.0, min(1.0, (b - py) / (sh * scale)))]
                boxes.append((box, float(s), int(c)))
            # NMS (IoU 0.45), same convention as the app
            boxes.sort(key=lambda x: -x[1])
            kept = []
            for box, s, c in boxes:
                if all(iou(box, kb[0]) <= 0.45 for kb in kept):
                    kept.append((box, s, c))
            for box, s, c in kept:
                dets.append({"box": box, "label": "rubbish" if c == 0 else str(c),
                             "confidence": s})
            out.write(json.dumps({"image": name, "detections": dets}) + "\n")
            print(f"ref: {name}: {len(dets)} detections")
    print(f"reference written to {out_path}")


def parse_sweep(spec):
    lo, hi, step = (float(x) for x in spec.split(":"))
    out, v = [], lo
    while v <= hi + 1e-9:
        out.append(round(v, 4))
        v += step
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--device", help="device harness_predictions.jsonl")
    ap.add_argument("--reference", help="reference predictions jsonl (parity, R5)")
    ap.add_argument("--labels", help="YOLO-format ground-truth label dir (accuracy, R6)")
    ap.add_argument("--sweep", default="0.20:0.60:0.05",
                    help="confidence sweep lo:hi:step (default 0.20:0.60:0.05)")
    ap.add_argument("--generate-reference", action="store_true")
    ap.add_argument("--model", help="tflite model (with --generate-reference)")
    ap.add_argument("--images", help="images dir (with --generate-reference)")
    ap.add_argument("--out", default="reference_predictions.jsonl")
    args = ap.parse_args()

    if args.generate_reference:
        if not (args.model and args.images):
            ap.error("--generate-reference needs --model and --images")
        generate_reference(args.model, args.images, args.out)
        return

    if not args.device:
        ap.error("--device is required (or use --generate-reference)")
    device = load_jsonl(args.device)
    print(f"device dump: {len(device)} images, "
          f"{sum(len(v) for v in device.values())} detections")

    ok = True
    if args.reference:
        ok = check_parity(device, load_jsonl(args.reference)) and ok
    if args.labels:
        check_accuracy(device, args.labels, parse_sweep(args.sweep))
    if not (args.reference or args.labels):
        print("nothing to compare: pass --reference and/or --labels")
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
